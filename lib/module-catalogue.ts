export type ModuleFilters = { query: string; category: string; state: string; role: string };
export const defaultModuleFilters: ModuleFilters = { query: '', category: 'all', state: 'all', role: 'all' };
export function filteredModules(filters: ModuleFilters) {
  const query = filters.query.trim().toLocaleLowerCase('bg');
  return schoolModules.filter(m =>
    (filters.category === 'all' || m.category === filters.category) &&
    (filters.state === 'all' || m.state === filters.state) &&
    (filters.role === 'all' || m.roles.includes(filters.role as Role)) &&
    [m.title, m.summary, m.current, ...m.remaining].join(' ').toLocaleLowerCase('bg').includes(query));
}
